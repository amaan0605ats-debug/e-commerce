export function getServiceBySlug(slug) {
  return services.find(s => s.slug === slug);
}

export function getRelatedServices(currentSlug, count = 4) {
  const current = getServiceBySlug(currentSlug);
  if (!current) return services.slice(0, count);
  
  const sameCategory = services.filter(s => s.category === current.category && s.slug !== currentSlug);
  const others = services.filter(s => s.category !== current.category && s.slug !== currentSlug);
  
  return [...sameCategory, ...others].slice(0, count);
}
